export function structure(base) {
  if (STRUCTURES[base]) return { fr: STRUCTURES[base][0], kind: STRUCTURES[base][1] };
  const m = base.match(/^(upper|lower) (.+)$/);
  if (m && DENTS[m[2]]) {
    return { fr: `${DENTS[m[2]]} ${m[1] === 'upper' ? 'supérieure' : 'inférieure'}`, kind: 'dent' };
  }
  return null;
}
